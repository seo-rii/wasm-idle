import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = new URL('../', import.meta.url);
/** @typedef {{path?: string; source: string; bytes: number; sha256: string}} SourceReceipt */
/** @type {{version: string; revision: string; baseUrl: string; anchor: SourceReceipt; license: SourceReceipt; headers: Array<SourceReceipt & {path: string}>}} */
const lock = JSON.parse(
	await readFile(new URL('scripts/clang-cpp-headers.lock.json', root), 'utf8')
);
const args = process.argv.slice(2);
const sourceDirIndex = args.indexOf('--source-dir');
const sourceDir = sourceDirIndex === -1 ? undefined : args[sourceDirIndex + 1];
if (sourceDirIndex !== -1 && (!sourceDir || sourceDir.startsWith('--'))) {
	throw new Error('--source-dir requires a pinned LLVM source checkout');
}
const remainingArgs =
	sourceDirIndex === -1
		? args
		: args.filter((_, index) => index !== sourceDirIndex && index !== sourceDirIndex + 1);
if (remainingArgs.some((arg) => arg !== '--check')) {
	throw new Error('Usage: sync-clang-cpp-headers.mjs [--source-dir DIR] [--check]');
}
/** @param {SourceReceipt} receipt */
async function readPinned(receipt) {
	let bytes;
	if (sourceDir) {
		bytes = await readFile(path.join(sourceDir, receipt.source));
	} else {
		const response = await fetch(new URL(receipt.source, lock.baseUrl), {
			signal: AbortSignal.timeout(60_000)
		});
		if (!response.ok) throw new Error(`${receipt.source}: HTTP ${response.status}`);
		bytes = Buffer.from(await response.arrayBuffer());
	}
	if (
		bytes.length !== receipt.bytes ||
		createHash('sha256').update(bytes).digest('hex') !== receipt.sha256
	) {
		throw new Error(`${receipt.source}: LLVM source receipt mismatch`);
	}
	return bytes.toString('utf8');
}

const anchor = await readPinned(lock.anchor);
/** @type {Record<string, string>} */
const headers = {};
for (let offset = 0; offset < lock.headers.length; offset += 4) {
	const batch = lock.headers.slice(offset, offset + 4);
	const contents = await Promise.all(batch.map(readPinned));
	for (let index = 0; index < batch.length; index++) headers[batch[index].path] = contents[index];
}
const license = await readPinned(lock.license);
if (license !== (await readFile(new URL('packages/llvm-core/LICENSE.llvm.txt', root), 'utf8'))) {
	throw new Error('The bundled LLVM license differs from the pinned source');
}
const generated = `// Generated by scripts/sync-clang-cpp-headers.mjs. Do not edit.
// LLVM ${lock.version}, Apache-2.0 WITH LLVM-exception; see LICENSE.llvm.txt.
// prettier-ignore
export const CLANG_CPP_HEADER_PROVENANCE = Object.freeze(${JSON.stringify({ name: 'clang', version: lock.version, revision: lock.revision })});
// prettier-ignore
export const CLANG_CPP_HEADER_ANCHOR = Object.freeze(${JSON.stringify({ path: lock.anchor.path, bytes: lock.anchor.bytes, sha256: lock.anchor.sha256 })});
// prettier-ignore
export const CLANG_CPP_HEADERS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(headers, null, '\t')});
`;
const output = new URL('packages/llvm-core/runtime/core/src/clang-cpp-headers.generated.ts', root);
const fixture = new URL(
	'packages/llvm-core/runtime/core/test/fixtures/clang-cpp-headers/ostream',
	root
);
if (args.includes('--check')) {
	if ((await readFile(output, 'utf8')) !== generated)
		throw new Error('Clang C++ headers are stale');
	if ((await readFile(fixture, 'utf8')) !== anchor)
		throw new Error('Clang C++ anchor fixture is stale');
} else {
	await writeFile(output, generated);
	await mkdir(new URL('.', fixture), { recursive: true });
	await writeFile(fixture, anchor);
}
console.log(
	`${args.includes('--check') ? 'Verified' : 'Synced'} ${lock.headers.length} pinned LLVM ${lock.version} C++ headers.`
);
