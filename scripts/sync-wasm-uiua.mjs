#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-uiua');
const defaultTarget = path.join(root, 'static/wasm-uiua');
const defaultVersionFile = path.join(root, 'src/lib/playground/wasmUiuaVersion.ts');
const sourceSha256 = 'c444c37f4342590ee616bce256d1b7f69dceaa96dea79542f5d4271e827d4a01';

/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.byteLength,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

/**
 * @param {string} directory
 * @returns {Promise<{ manifestBytes: Buffer; wasm: Buffer; license: Buffer; notices: Buffer; manifest: any }>}
 */
async function verifyBundle(directory) {
	const manifestBytes = await readFile(path.join(directory, 'runtime-build.json'));
	const manifest = JSON.parse(manifestBytes.toString('utf8'));
	if (
		manifest.schemaVersion !== 1 ||
		manifest.language !== 'UIUA' ||
		manifest.implementation?.name !== 'Uiua' ||
		manifest.implementation?.version !== '0.19.1' ||
		manifest.implementation?.sha256 !== sourceSha256 ||
		manifest.implementation?.revision !== 'face052446efdf2b0c31c3fb44a838fe793a0f83' ||
		manifest.producer?.target !== 'wasm32-wasip1' ||
		manifest.producer?.defaultFeatures !== false ||
		manifest.producer?.pathRemapping?.producer !== '/uiua-producer' ||
		manifest.producer?.pathRemapping?.cargo !== '/cargo' ||
		manifest.producer?.pathRemapping?.toolchain !== '/rust-toolchain' ||
		JSON.stringify(manifest.producer?.features) !== '["native_sys"]' ||
		!manifest.producer?.rustc?.startsWith('rustc 1.94.0 ')
	)
		throw new Error('Uiua runtime is not the pinned original console implementation');
	for (const name of [
		'Cargo.toml',
		'Cargo.lock',
		'src/main.rs',
		'patches/wasi-clock.patch',
		'build.py',
		'licenses/highway-1.3.0.txt'
	]) {
		const expected = manifest.producer.inputs?.[name];
		if (
			JSON.stringify(receipt(await readFile(path.join(producer, name)))) !==
			JSON.stringify(expected)
		)
			throw new Error(`Uiua build inputs changed: rebuild ${name} before syncing`);
	}
	const wasm = await readFile(path.join(directory, 'uiua.wasm'));
	const license = await readFile(path.join(directory, 'LICENSE.txt'));
	const notices = await readFile(path.join(directory, 'THIRD_PARTY_NOTICES.txt'));
	/** @type {Array<[string, Buffer]>} */
	const files = [
		['uiua.wasm', wasm],
		['LICENSE.txt', license],
		['THIRD_PARTY_NOTICES.txt', notices]
	];
	for (const [name, bytes] of files) {
		if (JSON.stringify(receipt(bytes)) !== JSON.stringify(manifest.artifacts?.[name]))
			throw new Error(`Uiua ${name} does not match its producer receipt`);
	}
	if (
		wasm.byteLength > 20 * 1024 * 1024 ||
		!wasm.subarray(0, 4).equals(Buffer.from([0, 97, 115, 109]))
	)
		throw new Error('Invalid Uiua WebAssembly artifact');
	return { manifestBytes, manifest, wasm, license, notices };
}

/**
 * Verify the committed interpreter; explicitly supplied producer output can refresh it.
 * @param {{ check?: boolean; sourceDir?: string; targetDir?: string; versionModulePath?: string }} options
 */
export async function syncWasmUiuaAssets({
	check = false,
	sourceDir,
	targetDir = defaultTarget,
	versionModulePath = defaultVersionFile
} = {}) {
	const source = sourceDir ?? targetDir;
	const bundle = await verifyBundle(source);
	const wasmReceipt = bundle.manifest.artifacts['uiua.wasm'];
	const profile =
		`// Generated by scripts/sync-wasm-uiua.mjs.\n` +
		`import type { WasiInterpreterProfile } from './wasiInterpreters';\n\n` +
		`export const WASM_UIUA_INTERPRETER = Object.freeze(${JSON.stringify(
			{
				id: 'UIUA',
				folder: 'wasm-uiua',
				fileName: 'uiua.wasm',
				sourcePath: 'main.ua',
				command: 'uiua',
				args: [],
				forwardProgramArgs: true,
				...wasmReceipt
			},
			null,
			2
		)} as const satisfies WasiInterpreterProfile);\n`;
	const profileBytes = Buffer.from(
		await format(profile, {
			...(await resolveConfig(versionModulePath)),
			parser: 'typescript'
		})
	);
	const outputs = new Map([
		[path.join(targetDir, 'uiua.wasm'), bundle.wasm],
		[path.join(targetDir, 'LICENSE.txt'), bundle.license],
		[path.join(targetDir, 'THIRD_PARTY_NOTICES.txt'), bundle.notices],
		[path.join(targetDir, 'runtime-build.json'), bundle.manifestBytes],
		[versionModulePath, profileBytes]
	]);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error(`Uiua runtime is stale: ${file}`);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return wasmReceipt;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const sourceIndex = process.argv.indexOf('--source');
	await syncWasmUiuaAssets({
		check: process.argv.includes('--check'),
		sourceDir: sourceIndex < 0 ? undefined : process.argv[sourceIndex + 1]
	});
	console.log('Verified original Uiua 0.19.1 WASI interpreter and producer inputs');
}
