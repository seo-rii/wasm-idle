import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
/** @typedef {{ source: string; bytes: number; sha256: string }} SourceReceipt */
/** @type {{ version: string; revision: string; baseUrl: string; compilerFlags: SourceReceipt; defines: string[]; license: SourceReceipt; headers: Array<SourceReceipt & { path: string }>; llvmDependency: { name: string; version: string; revision: string; baseUrl: string; header: SourceReceipt & { path: string } } }} */
const lock = JSON.parse(
	await readFile(new URL('scripts/clang-simd-headers.lock.json', root), 'utf8')
);
/** @param {Uint8Array} bytes */
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
/** @param {SourceReceipt} receipt @param {string} [baseUrl] */
const fetchPinned = async (receipt, baseUrl = lock.baseUrl) => {
	const response = await fetch(new URL(receipt.source, baseUrl), {
		signal: AbortSignal.timeout(60_000)
	});
	if (!response.ok) throw new Error(`${receipt.source}: HTTP ${response.status}`);
	const bytes = Buffer.from(await response.arrayBuffer());
	if (bytes.length !== receipt.bytes || sha256(bytes) !== receipt.sha256) {
		throw new Error(`${receipt.source}: upstream source receipt mismatch`);
	}
	return bytes.toString('utf8');
};

const compilerFlags = await fetchPinned(lock.compilerFlags);
const defines = [
	...compilerFlags.matchAll(/cflags \+= \['(-D__(?:SSE[0-9_]*|SSSE3|AVX2?)__=1)'\]/g)
].map((match) => match[1]);
if (JSON.stringify(defines) !== JSON.stringify(lock.defines)) {
	throw new Error(
		'SIMD defines differ from the pinned Emscripten SSE through AVX2 feature tower'
	);
}

/** @type {Record<string, string>} */
const headers = {};
for (let offset = 0; offset < lock.headers.length; offset += 4) {
	const batch = lock.headers.slice(offset, offset + 4);
	const sources = await Promise.all(batch.map((receipt) => fetchPinned(receipt)));
	for (let index = 0; index < batch.length; index++) {
		headers[batch[index].path] = sources[index];
	}
}
headers[lock.llvmDependency.header.path] = await fetchPinned(
	lock.llvmDependency.header,
	lock.llvmDependency.baseUrl
);
const license = await fetchPinned(lock.license);
const provenance = { name: 'emscripten', version: lock.version, revision: lock.revision };
const wasmProvenance = {
	name: lock.llvmDependency.name,
	version: lock.llvmDependency.version,
	revision: lock.llvmDependency.revision
};
const generated = `// Generated by scripts/sync-clang-simd-headers.mjs. Do not edit.
// Emscripten ${lock.version}, MIT OR NCSA; see LICENSE.emscripten.txt.
// LLVM ${lock.llvmDependency.version}, Apache-2.0 WITH LLVM-exception; see LICENSE.llvm.txt.
// prettier-ignore
export const CLANG_SIMD_HEADER_PROVENANCE = Object.freeze(${JSON.stringify(provenance, null, '\t')});
// prettier-ignore
export const CLANG_SIMD_WASM_HEADER_PROVENANCE = Object.freeze(${JSON.stringify(wasmProvenance, null, '\t')});
// prettier-ignore
export const CLANG_SIMD_DEFINES: readonly string[] = Object.freeze(${JSON.stringify(defines, null, '\t')});
// prettier-ignore
export const CLANG_SIMD_HEADERS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(headers, null, '\t')});
`;
await writeFile(
	new URL('packages/llvm-core/runtime/core/src/clang-simd-headers.generated.ts', root),
	generated
);
await writeFile(new URL('packages/llvm-core/LICENSE.emscripten.txt', root), license);
console.log(
	`Synced ${lock.headers.length} Emscripten ${lock.version} SIMD headers and the LLVM ${lock.llvmDependency.version} WebAssembly intrinsic header.`
);
