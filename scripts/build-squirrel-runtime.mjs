import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { homedir, tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const revision = 'f92bc298784ceea459b12e2de33bdff672bfeb83';
const sourcePath = 'runtimes/wasm-squirrel/vendor/squirrel-f92bc298.tar.gz';
const sourceHash = '722f1a5f271dfb7ac90a42d3789a861b381b4741499de29ce06d238384645f2d';
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
const run = (command, args) => {
	const result = spawnSync(command, args, { cwd: root, encoding: 'utf8' });
	if (result.status !== 0) throw new Error(`${command}: ${result.stderr || result.error}`);
	return result.stdout;
};

const source = await readFile(path.join(root, sourcePath));
if (hash(source) !== sourceHash) throw new Error('Squirrel source archive hash mismatch');
const sdk = process.env.WASI_SDK_PATH || path.join(homedir(), '.local/share/wasi-sdk-33');
const compiler = path.join(sdk, 'bin/clang++');
const compilerVersion = run(compiler, ['--version']).split('\n')[0];
if (!compilerVersion.startsWith('clang version 22.1.0-wasi-sdk')) {
	throw new Error('Squirrel requires wasi-sdk 33.0');
}
const temporary = await mkdtemp(path.join(tmpdir(), 'wasm-idle-squirrel-'));
try {
	run('tar', ['-xzf', path.join(root, sourcePath), '-C', temporary]);
	const upstream = path.join(temporary, `squirrel-${revision}`);
	const patchPath = 'runtimes/wasm-squirrel/stdin-eof.patch';
	run('patch', ['-d', upstream, '-p1', '-i', path.join(root, patchPath)]);
	const sources = [];
	for (const directory of ['squirrel', 'sqstdlib']) {
		for (const file of (await readdir(path.join(upstream, directory))).sort()) {
			if (file.endsWith('.cpp')) sources.push(path.join(upstream, directory, file));
		}
	}
	const flags = [
		'--target=wasm32-wasip1',
		'-std=c++11',
		'-O2',
		'-fno-rtti',
		'-fno-exceptions',
		'-mexception-handling',
		'-mllvm',
		'-wasm-enable-sjlj',
		'-mllvm',
		'-wasm-use-legacy-eh=true',
		'-lsetjmp',
		'-fno-ident',
		'-D_WASI_EMULATED_PROCESS_CLOCKS',
		'-lwasi-emulated-process-clocks',
		'-DSQUSEDOUBLE',
		'-Wl,--strip-all',
		'-Wl,-z,stack-size=1048576',
		'-Wl,--max-memory=67108864'
	];
	const destination = path.join(root, 'static/wasm-squirrel');
	await mkdir(destination, { recursive: true });
	const wasmPath = path.join(destination, 'squirrel.wasm');
	run(compiler, [
		...flags,
		'-I',
		path.join(upstream, 'include'),
		...sources,
		path.join(root, 'runtimes/wasm-squirrel/runner.cpp'),
		'-o',
		wasmPath
	]);
	const wasm = await readFile(wasmPath);
	const receipt = {
		format: 'wasm-squirrel-build-v1',
		version: '3.2',
		revision,
		repository: 'https://github.com/albertodemichelis/squirrel',
		source: { path: sourcePath, sha256: sourceHash },
		patches: [{ path: patchPath, sha256: hash(await readFile(path.join(root, patchPath))) }],
		runnerSha256: hash(await readFile(path.join(root, 'runtimes/wasm-squirrel/runner.cpp'))),
		toolchain: { name: 'wasi-sdk', version: '33.0', compiler: compilerVersion },
		flags,
		license: 'MIT',
		numericProfile: 'int32/float64',
		wasm: { path: 'squirrel.wasm', bytes: wasm.length, sha256: hash(wasm) }
	};
	await copyFile(path.join(upstream, 'COPYRIGHT'), path.join(destination, 'LICENSE'));
	await copyFile(
		path.join(upstream, 'COPYRIGHT'),
		path.join(root, 'runtimes/wasm-squirrel/LICENSE')
	);
	await writeFile(
		path.join(destination, 'runtime-build.json'),
		JSON.stringify(receipt, null, '\t') + '\n'
	);
	await writeFile(
		path.join(root, 'scripts/wasm-squirrel-assets.lock.json'),
		JSON.stringify(receipt, null, '\t') + '\n'
	);
	const profilePath = path.join(root, 'src/lib/playground/squirrelProfile.ts');
	await writeFile(
		profilePath,
		await format(
			`// Generated by scripts/build-squirrel-runtime.mjs.\nimport type { WasiInterpreterProfile } from './wasiInterpreters';\n\nexport const SQUIRREL_PROFILE: WasiInterpreterProfile = ${JSON.stringify({ id: 'SQUIRREL', folder: 'wasm-squirrel', fileName: 'squirrel.wasm', sourcePath: 'main.nut', command: 'squirrel', args: [], sha256: hash(wasm), bytes: wasm.length }, null, '\t')};\n`,
			{ ...(await resolveConfig(profilePath)), filepath: profilePath }
		)
	);
	console.log(`Built Squirrel 3.2: ${wasm.length} bytes (${hash(wasm)})`);
} finally {
	await rm(temporary, { recursive: true, force: true });
}
