import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { format } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
/** @param {Uint8Array} bytes */
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');

/**
 * Pin upstream bytes before adding a module factory around the official non-modular build.
 * @param {{ sourceDir?: string; targetDir?: string; versionModulePath?: string; fetchImpl?: typeof fetch }} [options]
 */
export async function syncWasmPariGpAssets({
	sourceDir,
	targetDir = path.join(root, 'static/wasm-parigp'),
	versionModulePath = path.join(root, 'src/lib/playground/wasmPariGpVersion.ts'),
	fetchImpl = fetch
} = {}) {
	const lock = JSON.parse(
		await readFile(new URL('./wasm-parigp-assets.lock.json', import.meta.url), 'utf8')
	);
	/** @type {Record<string, Uint8Array>} */
	const verified = {};
	for (const [name, receipt] of Object.entries(lock.assets)) {
		let bytes;
		if (sourceDir) bytes = await readFile(path.join(sourceDir, name));
		else {
			const response = await fetchImpl(receipt.url, {
				redirect: 'error',
				signal: AbortSignal.timeout(120000)
			});
			if (!response.ok) throw new Error(`PARI/GP ${name}: HTTP ${response.status}`);
			if (Number(response.headers.get('content-length')) > receipt.bytes)
				throw new Error(`PARI/GP ${name} exceeds pinned size`);
			bytes = new Uint8Array(await response.arrayBuffer());
		}
		if (bytes.length !== receipt.bytes || hash(bytes) !== receipt.sha256)
			throw new Error(`PARI/GP ${name} integrity mismatch`);
		verified[name] = bytes;
	}
	const original = new TextDecoder('utf-8', { fatal: true }).decode(verified['gp.js']);
	const javascript = Buffer.from(
		`// Official PARI/GP ${lock.version}, factory wrapper only.\nexport default function createPari(options) { return new Promise((resolve, reject) => {\nvar Module = { ...options, noInitialRun: true, onAbort: reject, onRuntimeInitialized() { Module.FS = FS; Module.wasmMemory = wasmMemory; resolve(Module); } };\n${original}\n}); }\n`
	);
	// Node writes a zero mtime in gzip headers by default.
	const wasm = gzipSync(verified['gp.wasm'], { level: 9 });
	const assets = {
		'gp.mjs': { bytes: javascript.length, sha256: hash(javascript) },
		'gp.wasm.gz.bin': { bytes: wasm.length, sha256: hash(wasm) }
	};
	const runtimeLock = { ...lock, delivery: assets };
	const workerSource = await readFile(
		new URL('./runtime-workers/wasm-parigp-runner-worker.js', import.meta.url),
		'utf8'
	);
	const worker = Buffer.from(
		workerSource.replace('__WASM_IDLE_PARIGP_ASSET_LOCK__', JSON.stringify(runtimeLock))
	);
	const profile = {
		...runtimeLock,
		workerReceipt: { bytes: worker.length, sha256: hash(worker) }
	};
	const version = await format(
		`// Generated by sync:wasm-parigp.\nexport const WASM_PARIGP_PROFILE = ${JSON.stringify(profile)} as const;\n`,
		{
			parser: 'typescript',
			useTabs: true,
			singleQuote: true,
			trailingComma: 'none',
			printWidth: 100
		}
	);
	await mkdir(targetDir, { recursive: true });
	await writeFile(path.join(targetDir, 'gp.mjs'), javascript);
	await writeFile(path.join(targetDir, 'gp.wasm.gz.bin'), wasm);
	await writeFile(path.join(targetDir, 'runner-worker.js'), worker);
	await copyFile(
		path.join(root, 'runtimes/wasm-pari-gp/COPYING'),
		path.join(targetDir, 'COPYING')
	);
	await writeFile(
		path.join(targetDir, 'runtime-build.json'),
		JSON.stringify(profile, null, '\t') + '\n'
	);
	await writeFile(versionModulePath, version);
	return { targetDir, version: lock.version };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	console.log(await syncWasmPariGpAssets({ sourceDir: process.env.WASM_PARIGP_SOURCE_DIR }));
}
