import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync, gunzipSync } from 'node:zlib';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';
import { extractPkgSnapshot } from './sync-wasm-grain.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LOCK = path.join(ROOT, 'scripts/grain-lsp-assets.lock.json');
const OUTPUT = path.join(ROOT, 'static/wasm-grain-lsp');
const PROFILE = path.join(ROOT, 'packages/lsp/src/grain/profile.ts');
const receipt = (bytes) => ({
	bytes: bytes.length,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

export function verifyGrainLspAsset(bytes, expected, label) {
	if (bytes.length !== expected.bytes || receipt(bytes).sha256 !== expected.sha256)
		throw new Error(`${label} failed pinned size/SHA-256 verification`);
	return bytes;
}

export async function syncGrainLsp({ releaseBinary, updateLock = false } = {}) {
	const lock = JSON.parse(await readFile(LOCK, 'utf8'));
	const binaryPath = releaseBinary || path.join(ROOT, '.cache/grain-lsp/grain-linux-x64');
	let binary;
	try {
		binary = await readFile(binaryPath);
	} catch (error) {
		if (releaseBinary || error.code !== 'ENOENT') throw error;
		const response = await fetch(lock.release.url, { signal: AbortSignal.timeout(120_000) });
		if (!response.ok) throw new Error(`Grain release HTTP ${response.status}`);
		const chunks = [];
		let length = 0;
		for await (const chunk of response.body) {
			length += chunk.length;
			if (length > lock.release.bytes) throw new Error('Grain release exceeds pinned size');
			chunks.push(chunk);
		}
		binary = Buffer.concat(chunks);
		verifyGrainLspAsset(binary, lock.release, 'Grain release');
		await mkdir(path.dirname(binaryPath), { recursive: true });
		await writeFile(binaryPath, binary);
	}
	verifyGrainLspAsset(binary, lock.release, 'Grain release');
	const snapshot = extractPkgSnapshot(binary);
	const server = snapshot.get(lock.snapshotPath);
	if (!server) throw new Error('Original grainlsp.bc.js is missing from the release');
	verifyGrainLspAsset(server, lock.server, 'Original Grain LSP');
	const stdlib = await readFile(path.join(ROOT, 'static/wasm-grain/stdlib.pack.gz.bin'));
	verifyGrainLspAsset(stdlib, lock.stdlibStorage, 'Grain standard library storage');
	verifyGrainLspAsset(
		gunzipSync(stdlib, { maxOutputLength: lock.stdlib.bytes }),
		lock.stdlib,
		'Grain standard library'
	);
	const host = await build({
		stdin: {
			contents:
				"export { createGrainCompilerHost, readGrainStdlibPack, GRAIN_STDLIB_ROOT, GRAIN_STDLIB_SOURCE_MTIME_MS, GRAIN_STDLIB_OBJECT_MTIME_MS } from './scripts/runtime-workers/grain-host.mjs';",
			resolveDir: ROOT
		},
		bundle: true,
		write: false,
		platform: 'browser',
		format: 'esm',
		target: 'es2022',
		minify: true
	});
	const assets = {
		'grainlsp.js.gz.bin': gzipSync(server, { level: 9 }),
		'stdlib.pack.gz.bin': stdlib,
		'host.mjs': host.outputFiles[0].contents,
		'LICENSE-grain-compiler.txt': await readFile(
			path.join(ROOT, 'static/wasm-grain/LICENSE-grain-compiler.txt')
		),
		'LICENSE-grain-stdlib.txt': await readFile(
			path.join(ROOT, 'static/wasm-grain/LICENSE-grain-stdlib.txt')
		)
	};
	const receipts = Object.fromEntries(
		Object.entries(assets).map(([name, bytes]) => [name, receipt(bytes)])
	);
	if (updateLock) {
		lock.assets = receipts;
		await writeFile(LOCK, `${JSON.stringify(lock, null, '\t')}\n`);
	} else {
		for (const [name, bytes] of Object.entries(assets)) {
			if (!lock.assets[name]) throw new Error(`Missing asset receipt: ${name}`);
			verifyGrainLspAsset(bytes, lock.assets[name], name);
		}
	}
	await mkdir(OUTPUT, { recursive: true });
	for (const [name, bytes] of Object.entries(assets))
		await writeFile(path.join(OUTPUT, name), bytes);
	const profile = {
		revision: lock.release.revision,
		server: lock.server,
		stdlib: lock.stdlib,
		assets: receipts
	};
	await mkdir(path.dirname(PROFILE), { recursive: true });
	await writeFile(
		PROFILE,
		await format(
			`// Generated by scripts/sync-grain-lsp.mjs.\nexport const GRAIN_LSP_PROFILE = ${JSON.stringify(profile, null, '\t')} as const;\n`,
			{ ...(await resolveConfig(PROFILE)), parser: 'typescript' }
		)
	);
	return { output: OUTPUT, profile };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const index = process.argv.indexOf('--release-binary');
	console.log(
		JSON.stringify(
			await syncGrainLsp({
				releaseBinary: index >= 0 ? process.argv[index + 1] : undefined,
				updateLock: process.argv.includes('--update-lock')
			})
		)
	);
}
