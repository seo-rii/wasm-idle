#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const execute = promisify(execFile);
/** @param {Uint8Array} data */
const receipt = (data) => ({
	bytes: data.byteLength,
	sha256: createHash('sha256').update(data).digest('hex')
});

/** @param {string} targetDir */
async function downloadOfficialAssets(targetDir) {
	await execute(
		'python3',
		[path.join(root, 'runtimes/wasm-dart/prepare.py'), '--output', targetDir],
		{
			timeout: 180_000,
			maxBuffer: 1024 * 1024
		}
	);
}

/** @param {{check?: boolean; targetDir?: string; profilePath?: string; prepareAssets?: (targetDir: string) => Promise<void>}} options */
export async function syncWasmDartAssets({
	check = false,
	targetDir = path.join(root, 'static/wasm-dart'),
	profilePath = path.join(root, 'src/lib/playground/wasmDartVersion.ts'),
	prepareAssets = downloadOfficialAssets
} = {}) {
	if (!check) {
		await mkdir(targetDir, { recursive: true });
		for (const name of ['upstream.json', 'LICENSE.txt', 'version.json']) {
			try {
				await readFile(path.join(targetDir, name));
			} catch (error) {
				if (
					!error ||
					typeof error !== 'object' ||
					!('code' in error) ||
					error.code !== 'ENOENT'
				)
					throw error;
				await copyFile(
					path.join(root, 'static/wasm-dart', name),
					path.join(targetDir, name)
				);
			}
		}
	}
	const manifest = JSON.parse(await readFile(path.join(targetDir, 'upstream.json'), 'utf8'));
	if (
		manifest.version !== '3.14.0' ||
		manifest.revision !== 'fa8c1270c374c1346931583a17c3b7f278d3822d' ||
		manifest.archive?.sha256 !==
			'a47fad5844f91cfce800a20e2b3442847bf56b3332892cf8000b2abd0dd8a5f9'
	)
		throw new Error('Dart runtime is not the pinned official implementation');
	const assets = Object.entries({
		...manifest.assets,
		'LICENSE.txt': { bytes: manifest.license.bytes, sha256: manifest.license.sha256 }
	});
	/** @type {string[]} */
	const missing = [];
	for (const [name, expected] of assets) {
		try {
			if (
				JSON.stringify(receipt(await readFile(path.join(targetDir, name)))) !==
				JSON.stringify(expected)
			)
				throw new Error(`Dart asset does not match its source receipt: ${name}`);
		} catch (error) {
			if (
				!error ||
				typeof error !== 'object' ||
				!('code' in error) ||
				error.code !== 'ENOENT'
			)
				throw error;
			missing.push(name);
		}
	}
	if (missing.length) {
		if (check)
			throw new Error(
				`Missing Dart assets: ${missing.join(', ')}; run node scripts/sync-wasm-dart.mjs`
			);
		await prepareAssets(targetDir);
		for (const [name, expected] of assets)
			if (
				JSON.stringify(receipt(await readFile(path.join(targetDir, name)))) !==
				JSON.stringify(expected)
			)
				throw new Error(`Dart asset does not match its source receipt: ${name}`);
	}
	const configuration = await resolveConfig(path.join(root, 'package.json'));
	const host = await readFile(path.join(root, 'runtimes/wasm-dart/host.dart'), 'utf8');
	const template = await readFile(
		path.join(root, 'scripts/runtime-workers/wasm-dart-runner-worker.js'),
		'utf8'
	);
	const runner = await format(
		template
			.replace('__WASM_IDLE_DART_DISTRIBUTION__', JSON.stringify(manifest))
			.replace('__WASM_IDLE_DART_HOST__', JSON.stringify(host)),
		{ ...configuration, parser: 'babel' }
	);
	const profile = await format(
		`// Generated by scripts/sync-wasm-dart.mjs.\nexport const WASM_DART_RUNTIME = Object.freeze(${JSON.stringify({ version: manifest.version, folder: 'wasm-dart', worker: receipt(Buffer.from(runner)) })} as const);\n`,
		{ ...configuration, parser: 'typescript' }
	);
	for (const [file, content] of [
		[path.join(targetDir, 'runner-worker.js'), runner],
		[profilePath, profile]
	]) {
		if (check) {
			if ((await readFile(file, 'utf8')) !== content)
				throw new Error(`Dart generated asset is stale: ${file}`);
		} else await writeFile(file, content);
	}
	return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await syncWasmDartAssets({ check: process.argv.includes('--check') });
	console.log('Verified original Dart 3.14.0 browser compiler and generated host');
}
