#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-coq');
/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.length,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

/** @param {{sourceRoot?: string; profile: object}} options */
export async function buildCoqHostWorker({ sourceRoot = root, profile }) {
	const bundled = await build({
		absWorkingDir: sourceRoot,
		preserveSymlinks: true,
		tsconfigRaw: { compilerOptions: { alwaysStrict: true } },
		entryPoints: [path.join(sourceRoot, 'scripts/runtime-workers/wasm-coq-runner-worker.js')],
		bundle: true,
		write: false,
		platform: 'browser',
		format: 'iife',
		target: 'es2022',
		legalComments: 'inline',
		define: { __WASM_IDLE_COQ_PROFILE__: JSON.stringify(profile) }
	});
	return Buffer.from(bundled.outputFiles[0].contents);
}

/**
 * Page builds verify committed release bytes; only --download accesses upstream.
 * @param {{check?: boolean; download?: boolean; sourceDir?: string; targetDir?: string; versionModulePath?: string}} [options]
 */
export async function syncWasmCoqAssets({
	check = false,
	download = false,
	sourceDir,
	targetDir = path.join(root, 'static/wasm-coq'),
	versionModulePath = path.join(root, 'src/lib/playground/wasmCoqVersion.ts')
} = {}) {
	const pin = JSON.parse(await readFile(path.join(producer, 'upstream.json'), 'utf8'));
	if (
		pin.port.revision !== '7ca41fe7432c1dd2951d4aa42f5216e7bdb11990' ||
		pin.implementation.revision !== '18722d285c34aee39f344c080ccfebe02fd974ba'
	)
		throw new Error('Coq release pin changed');
	const profile = { profileId: pin.profileId, assets: pin.assets, archives: pin.archives };
	const outputs = new Map();
	for (const [name, expected] of Object.entries(pin.assets)) {
		let bytes;
		if (download) {
			const response = await fetch(expected.url, { redirect: 'error' });
			if (!response.ok) throw new Error(`Coq download failed: ${response.status}`);
			bytes = Buffer.from(await response.arrayBuffer());
		} else bytes = await readFile(path.join(sourceDir || targetDir, name));
		const actual = receipt(bytes);
		if (actual.bytes !== expected.bytes || actual.sha256 !== expected.sha256)
			throw new Error(`Coq pinned asset changed: ${name}`);
		outputs.set(path.join(targetDir, name), bytes);
	}
	const worker = await buildCoqHostWorker({ profile });
	const workerReceipt = receipt(worker);
	outputs.set(path.join(targetDir, 'runner-worker.js'), worker);
	for (const [name, expected] of Object.entries(pin.notices)) {
		const bytes = await readFile(path.join(producer, name));
		if (JSON.stringify(receipt(bytes)) !== JSON.stringify(expected))
			throw new Error(`Coq notice changed: ${name}`);
		outputs.set(path.join(targetDir, name), bytes);
	}
	/** @type {Record<string, {bytes: number; sha256: string}>} */
	const inputs = {};
	for (const name of [
		'upstream.json',
		'upstream-build.sh',
		'upstream-build.md',
		'upstream.Makefile',
		'upstream.jscoq.opam',
		'upstream.package.json',
		'upstream-toolchain-setup.sh',
		'trampoline.patch',
		'fold.patch',
		'timeout.patch'
	])
		inputs[name] = receipt(await readFile(path.join(producer, name)));
	const manifest = Buffer.from(
		JSON.stringify({ ...pin, worker: workerReceipt, inputs }, null, 2) + '\n'
	);
	outputs.set(path.join(targetDir, 'runtime-build.json'), manifest);
	outputs.set(
		versionModulePath,
		Buffer.from(
			await format(
				`// Generated by scripts/sync-wasm-coq.mjs.\nexport const COQ_PROFILE = ${JSON.stringify(profile)} as const;\nexport const COQ_WORKER_RECEIPT = ${JSON.stringify(workerReceipt)} as const;\nexport const COQ_MANIFEST_RECEIPT = ${JSON.stringify(receipt(manifest))} as const;\n`,
				{ ...(await resolveConfig(versionModulePath)), parser: 'typescript' }
			)
		)
	);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error(`Stale Coq runtime: ${file}`);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return { profile, workerReceipt, manifestReceipt: receipt(manifest) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await syncWasmCoqAssets({
		check: process.argv.includes('--check'),
		download: process.argv.includes('--download')
	});
	console.log('Verified original jsCoq kernel and matching Coq 8.17.1 standard library');
}
