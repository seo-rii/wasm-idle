import { createHash, randomUUID } from 'node:crypto';
import { lstat, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
/** @param {Uint8Array} bytes */
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');

// The reviewed lock pins the complete producer receipt, including validation inputs
// and evidence. A different build requires an explicit lock update, never trust-on-sync.
/** @param {{ sourceDir?: string; targetDir?: string; versionModulePath?: string }} options */
export async function syncWasmLfortranAssets({
	sourceDir,
	targetDir = path.join(root, 'static/wasm-lfortran'),
	versionModulePath = path.join(root, 'src/lib/playground/wasmLfortranVersion.ts')
} = {}) {
	if (!sourceDir)
		throw new Error(
			'LFortran sync requires the producer artifact directory as the source argument.'
		);
	const lock = JSON.parse(
		await readFile(new URL('./wasm-lfortran-assets.lock.json', import.meta.url), 'utf8')
	);
	const verified = new Map();
	for (const [name, receipt] of Object.entries(lock.assets)) {
		const file = path.join(sourceDir, name);
		const stat = await lstat(file);
		if (!stat.isFile() || stat.size !== receipt.bytes)
			throw new Error(`LFortran ${name} size/type mismatch.`);
		const bytes = await readFile(file);
		if (digest(bytes) !== receipt.sha256) throw new Error(`LFortran ${name} SHA-256 mismatch.`);
		verified.set(name, bytes);
	}
	const receipt = JSON.parse(verified.get('producer-receipt.json').toString('utf8'));
	if (
		receipt.producerId !== 'wasm-llvm/lfortran-browser' ||
		receipt.source !== lock.source ||
		receipt.backend !== 'llvm' ||
		receipt.host !== 'emscripten' ||
		receipt.execution !== 'dynamic-side-module' ||
		receipt.validation?.passed !== true
	) {
		throw new Error('LFortran producer receipt does not match the reviewed LLVM evaluator.');
	}
	const workerSource = await readFile(
		new URL('./runtime-workers/wasm-lfortran-runner-worker.js', import.meta.url),
		'utf8'
	);
	const placeholder = '__WASM_IDLE_LFORTRAN_ASSET_LOCK__';
	if (workerSource.split(placeholder).length !== 2)
		throw new Error('LFortran worker must contain exactly one asset-lock placeholder.');
	const worker = Buffer.from(workerSource.replace(placeholder, JSON.stringify(lock)));
	const workerReceipt = { bytes: worker.length, sha256: digest(worker) };
	const version = await format(
		`// Generated by sync:wasm-lfortran from the reviewed asset lock.\nexport const WASM_LFORTRAN_PROFILE = ${JSON.stringify({ ...lock, workerReceipt }, null, '\t')} as const;\n`,
		{
			parser: 'typescript',
			printWidth: 100,
			singleQuote: true,
			tabWidth: 4,
			trailingComma: 'none',
			useTabs: true
		}
	);
	await publishLfortranBundle({ targetDir, versionModulePath, verified, worker, version });
	return {
		sourceDir: path.resolve(sourceDir),
		targetDir: path.resolve(targetDir),
		source: lock.source,
		workerReceipt
	};
}

/** Publish an already-verified bundle and its profile as one rollback-safe transaction.
 * @param {{ targetDir: string; versionModulePath: string; verified: Map<string, Uint8Array>; worker: Uint8Array; version: string }} options
 */
export async function publishLfortranBundle({
	targetDir,
	versionModulePath,
	verified,
	worker,
	version
}) {
	const staging = `${path.resolve(targetDir)}.staging-${randomUUID()}`;
	const backup = `${path.resolve(targetDir)}.backup-${randomUUID()}`;
	const stagedVersion = `${path.resolve(versionModulePath)}.staging-${randomUUID()}`;
	await mkdir(staging, { recursive: true });
	let moved = false;
	let published = false;
	let complete = false;
	try {
		for (const [name, bytes] of verified) {
			await writeFile(
				path.join(staging, name === 'lfortran.data' ? 'lfortran.data.bin' : name),
				bytes
			);
		}
		await writeFile(path.join(staging, 'runner-worker.js'), worker);
		await mkdir(path.dirname(versionModulePath), { recursive: true });
		await writeFile(stagedVersion, version, { flag: 'wx' });
		try {
			await rename(targetDir, backup);
			moved = true;
		} catch (error) {
			if (!(error instanceof Error) || !('code' in error) || error.code !== 'ENOENT')
				throw error;
		}
		await rename(staging, targetDir);
		published = true;
		await rename(stagedVersion, versionModulePath);
		complete = true;
	} catch (error) {
		if (published) await rm(targetDir, { recursive: true, force: true });
		if (moved) await rename(backup, targetDir);
		throw error;
	} finally {
		await rm(staging, { recursive: true, force: true });
		await rm(stagedVersion, { force: true });
		if (complete && moved) await rm(backup, { recursive: true });
	}
}
