import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { format, resolveConfig } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
const producer = path.join(root, 'runtimes/wasm-wren');
const lock = JSON.parse(await readFile(path.join(producer, 'upstream.lock.json'), 'utf8'));
const hash = (bytes) => createHash('sha256').update(bytes).digest('hex');
for (const file of lock.files) {
	const bytes = await readFile(path.join(producer, 'vendor', file.path));
	if (bytes.length !== file.bytes || hash(bytes) !== file.sha256)
		throw new Error(`Upstream receipt mismatch: ${file.path}`);
}
const sdk = process.env.WASI_SDK_PATH;
if (!sdk) throw new Error('Set WASI_SDK_PATH to wasi-sdk 33.0');
const clang = path.join(sdk, 'bin/clang');
const version = spawnSync(clang, ['--version'], { encoding: 'utf8' });
if (version.status !== 0) throw new Error('Could not execute wasi-sdk clang');
const compilerVersion = version.stdout.split('\n')[0];
if (!compilerVersion.startsWith('clang version 22.1.0-wasi-sdk'))
	throw new Error('Wren requires wasi-sdk 33.0');
const output = path.join(root, 'static/wasm-wren');
await mkdir(output, { recursive: true });
const sources = lock.files
	.filter(({ path }) => path.endsWith('.c'))
	.map(({ path: name }) => path.join(producer, 'vendor', name));
const args = [
	'--target=wasm32-wasip1',
	'-std=c99',
	'-Oz',
	'-DWREN_COMPUTED_GOTO=0',
	'-fno-strict-aliasing',
	'-D_WASI_EMULATED_PROCESS_CLOCKS',
	'-I',
	path.join(producer, 'vendor/src/include'),
	'-I',
	path.join(producer, 'vendor/src/vm'),
	'-I',
	path.join(producer, 'vendor/src/optional'),
	path.join(producer, 'runner.c'),
	...sources,
	'-Wl,-z,stack-size=1048576',
	'-Wl,--max-memory=268435456',
	'-Wl,--strip-all',
	'-lwasi-emulated-process-clocks',
	'-lm',
	'-o',
	path.join(output, 'wren.wasm')
];
const build = spawnSync(clang, args, { stdio: 'inherit' });
if (build.status !== 0) throw new Error(`Wren build failed (${build.status})`);
const bytes = await readFile(path.join(output, 'wren.wasm'));
const receipt = { sha256: hash(bytes), bytes: bytes.length };
const buildLock = {
	schemaVersion: 1,
	upstream: { repository: lock.repository, revision: lock.revision, version: lock.version },
	toolchain: { name: 'wasi-sdk', version: '33.0', compiler: compilerVersion },
	flags: args.filter((arg) => !arg.startsWith(root) && !['-I', '-o'].includes(arg)),
	host: {
		path: 'runtimes/wasm-wren/runner.c',
		sha256: hash(await readFile(path.join(producer, 'runner.c')))
	},
	assets: { 'wren.wasm': receipt }
};
await writeFile(
	path.join(root, 'scripts/wasm-wren-assets.lock.json'),
	JSON.stringify(buildLock, null, '\t') + '\n'
);
await writeFile(
	path.join(output, 'runtime-build.json'),
	JSON.stringify(buildLock, null, '\t') + '\n'
);
await writeFile(
	path.join(output, 'LICENSE'),
	await readFile(path.join(producer, 'vendor/LICENSE'))
);
const profile = {
	id: 'WREN',
	folder: 'wasm-wren',
	fileName: 'wren.wasm',
	sourcePath: 'main.wren',
	command: 'wren',
	args: [],
	...receipt
};
await writeFile(
	path.join(root, 'src/lib/playground/wasmWrenVersion.ts'),
	await format(
		"// Generated by scripts/build-wasm-wren.mjs.\nimport type { WasiInterpreterProfile } from './wasiInterpreters';\n\n" +
			`export const WREN_INTERPRETER: WasiInterpreterProfile = ${JSON.stringify(profile, null, '\t')};\n`,
		{ ...(await resolveConfig(path.join(root, '.prettierrc'))), parser: 'typescript' }
	)
);
console.log(`Built upstream Wren ${lock.version}: ${bytes.length} bytes (${receipt.sha256})`);
