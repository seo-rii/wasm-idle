import { createHash } from 'node:crypto';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';
import { format, resolveConfig } from 'prettier';

const ROOT = fileURLToPath(new URL('../', import.meta.url));
const LOCK = path.join(ROOT, 'scripts/nim-lsp-assets.lock.json');
const PROFILE = path.join(ROOT, 'packages/lsp/src/nim/profile.ts');
const receipt = (bytes) => ({
	bytes: bytes.length,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

export function verifyNimLspAsset(bytes, expected, label) {
	if (!expected || bytes.length !== expected.bytes || receipt(bytes).sha256 !== expected.sha256)
		throw new Error(`${label} failed pinned size/SHA-256 verification`);
	return bytes;
}

export async function syncNimLsp({
	producerDir = path.join(ROOT, '.cache/nim-lsp/browser'),
	targetDir = path.join(ROOT, 'static/wasm-nim-lsp'),
	buildProducer = true,
	updateLock = false
} = {}) {
	if (buildProducer) {
		await new Promise((resolve, reject) => {
			const child = spawn(
				'python3',
				[path.join(ROOT, 'producers/nim-lsp/build.py'), '--out-dir', producerDir],
				{ cwd: ROOT, stdio: 'inherit' }
			);
			child.on('error', reject);
			child.on('exit', (code) =>
				code === 0 ? resolve() : reject(new Error(`Nim LSP producer exited ${code}`))
			);
		});
	}
	const lock = JSON.parse(await readFile(LOCK, 'utf8'));
	const producer = JSON.parse(
		await readFile(path.join(producerDir, 'producer-manifest.json'), 'utf8')
	);
	if (producer.native) throw new Error('Expected the browser Nim LSP producer');
	const assets = {};
	const logical = {};
	for (const name of ['nimlsp.mjs', 'nimlsp.wasm', 'stdlib.json']) {
		const bytes = verifyNimLspAsset(
			await readFile(path.join(producerDir, name)),
			producer.files[name],
			name
		);
		const storage = name + '.gz.bin';
		logical[storage] = receipt(bytes);
		if (!updateLock) verifyNimLspAsset(bytes, lock.logical?.[storage], name);
		assets[storage] = gzipSync(bytes, { level: 9 });
	}
	for (const name of [
		'LICENSE.nim.txt',
		'LICENSE.nimlsp.txt',
		'LICENSE.asynctools.txt',
		'LICENSE.emscripten.txt',
		'LICENSE.musl.txt',
		'NOTICES.md'
	]) {
		assets[name] = verifyNimLspAsset(
			await readFile(path.join(producerDir, name)),
			producer.files[name],
			name
		);
	}
	assets['SOURCE.txt'] = Buffer.from(
		`Original nimlsp ${lock.inputs.nimlsp.version} (${lock.inputs.nimlsp.revision})\n` +
			Object.entries(lock.inputs)
				.map(
					([name, input]) =>
						`${input.repository}/tree/${name === 'emscripten' ? input.version : input.revision}\nArchive: ${input.url}\nSHA-256: ${input.sha256}\n`
				)
				.join('') +
			'Build: python3 producers/nim-lsp/build.py (Linux x86_64 bootstrap; Emscripten 6.0.0, SOURCE_DATE_EPOCH=0, jobs=2, bwrap private canonical build paths).\n' +
			'The original Nim compiler/nimsuggest parser and nimlsp handlers are preserved. Browser adaptations select the existing synchronous stdio branch, reject unavailable asynchronous subprocess waits, and use the official ORC/malloc runtime for WebAssembly. Private Linux mount namespaces expose the original inputs at /tmp/nim-lsp-build so the original compiler generates deterministic assertion paths and type signature hashes without any generated C modification. No language analysis is implemented by the adapter.\n' +
			'Filesystem/stdin/stdout adapter: packages/lsp/src/nim in wasm-idle.\n'
	);
	const receipts = Object.fromEntries(
		Object.entries(assets).map(([name, bytes]) => [name, receipt(bytes)])
	);
	if (updateLock) {
		lock.assets = receipts;
		lock.logical = logical;
		await writeFile(LOCK, JSON.stringify(lock, null, '\t') + '\n');
	} else
		for (const [name, bytes] of Object.entries(assets))
			verifyNimLspAsset(bytes, lock.assets[name], name);
	const profile = {
		version: lock.inputs.nimlsp.version,
		revision: lock.inputs.nimlsp.revision,
		compiler: {
			version: lock.inputs.nim.version,
			revision: lock.inputs.nim.revision,
			memoryManager: 'orc'
		},
		assets: receipts,
		logical
	};
	await mkdir(targetDir, { recursive: true });
	for (const [name, bytes] of Object.entries(assets))
		await writeFile(path.join(targetDir, name), bytes);
	await writeFile(
		path.join(targetDir, 'runtime-manifest.json'),
		JSON.stringify({ format: 'wasm-idle-nim-lsp-v1', ...profile }, null, '\t') + '\n'
	);
	await mkdir(path.dirname(PROFILE), { recursive: true });
	await writeFile(
		PROFILE,
		await format(
			`// Generated by scripts/sync-nim-lsp.mjs.\nexport const NIM_LSP_PROFILE = ${JSON.stringify(profile)} as const;\n`,
			{ ...(await resolveConfig(PROFILE)), parser: 'typescript' }
		)
	);
	return { targetDir, profile };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url))
	console.log(await syncNimLsp({ updateLock: process.argv.includes('--update-lock') }));
