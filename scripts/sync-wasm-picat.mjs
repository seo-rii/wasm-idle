import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'fflate';
import { format } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
/** @param {Uint8Array} bytes */
const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
/** @param {{sourceDir?:string,targetDir?:string,versionModulePath?:string,fetchImpl?:typeof fetch}} [options] */
export async function syncWasmPicatAssets({
	sourceDir,
	targetDir = path.join(root, 'static/wasm-picat'),
	versionModulePath = path.join(root, 'src/lib/playground/wasmPicatVersion.ts'),
	fetchImpl = fetch
} = {}) {
	const lock = JSON.parse(
		await readFile(new URL('./wasm-picat-assets.lock.json', import.meta.url), 'utf8')
	);
	/** @type {Record<string, Uint8Array>} */
	const verified = {};
	for (const [name, receipt] of Object.entries(lock.upstream)) {
		const bytes = sourceDir
			? await readFile(path.join(sourceDir, name))
			: new Uint8Array(
					await (
						await fetchImpl(new URL(name, lock.baseUrl), {
							redirect: 'error',
							signal: AbortSignal.timeout(120000)
						})
					).arrayBuffer()
				);
		if (bytes.length !== receipt.bytes || digest(bytes) !== receipt.sha256)
			throw new Error(`Picat ${name} receipt mismatch`);
		verified[name] = bytes;
	}
	const assets = {
		'picat.mjs': Buffer.from(
			new TextDecoder('utf-8', { fatal: true }).decode(verified['picat.js']) +
				'\nexport default PicatWasm;\n'
		),
		'picat.wasm': verified['picat.wasm'],
		'picat.data': verified['picat.data']
	};
	for (const [name, bytes] of Object.entries(assets)) {
		if (bytes.length !== lock.assets[name].bytes || digest(bytes) !== lock.assets[name].sha256)
			throw new Error(`Picat derived ${name} receipt mismatch`);
	}
	const source = await readFile(
		new URL('./runtime-workers/wasm-picat-runner-worker.js', import.meta.url),
		'utf8'
	);
	const placeholder = '__WASM_IDLE_PICAT_ASSET_LOCK__';
	if (source.split(placeholder).length !== 2)
		throw new Error('Picat worker lock placeholder mismatch');
	const worker = Buffer.from(
		source.replace(placeholder, JSON.stringify({ assets: lock.assets }))
	);
	const workerReceipt = { bytes: worker.length, sha256: digest(worker) };
	const profile = { ...lock, workerReceipt };
	await mkdir(targetDir, { recursive: true });
	for (const [name, bytes] of Object.entries(assets)) {
		const stored = name.endsWith('.mjs') ? bytes : gzipSync(bytes, { level: 9, mtime: 0 });
		const file = name.endsWith('.mjs') ? name : name + '.gz.bin';
		if (
			stored.length !== lock.storage[file].bytes ||
			digest(stored) !== lock.storage[file].sha256
		)
			throw new Error(`Picat ${file} storage mismatch`);
		await writeFile(path.join(targetDir, file), stored);
	}
	for (const [name, expected] of Object.entries(lock.notices)) {
		const bytes = await readFile(path.join(root, 'runtimes/wasm-picat', name));
		if (bytes.length !== expected.bytes || digest(bytes) !== expected.sha256)
			throw new Error(`Picat ${name} notice mismatch`);
		await writeFile(path.join(targetDir, name), bytes);
	}
	await writeFile(path.join(targetDir, 'runner-worker.js'), worker);
	await writeFile(
		versionModulePath,
		await format(
			`// Generated by sync:wasm-picat.\nexport const WASM_PICAT_PROFILE = ${JSON.stringify(profile)} as const;\n`,
			{
				parser: 'typescript',
				useTabs: true,
				singleQuote: true,
				trailingComma: 'none',
				printWidth: 100
			}
		)
	);
	return { targetDir, workerReceipt };
}
if (process.argv[1] === fileURLToPath(import.meta.url)) console.log(await syncWasmPicatAssets());
