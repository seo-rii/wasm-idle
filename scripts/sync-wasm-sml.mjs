#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-sml');
const defaultTarget = path.join(root, 'static/wasm-sml');
const defaultVersionFile = path.join(root, 'src/lib/playground/wasmSmlVersion.ts');
const sourceSha256 = '819f3c90bf253df54a23ec074caf6859162004331a713f754393e25f87917b67';

/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.byteLength,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

/**
 * @param {string} directory
 * @returns {Promise<{ manifestBytes: Buffer; wasm: Buffer; license: Buffer; notices: Buffer; manifest: any }>}
 */
async function verifyBundle(directory) {
	const manifestBytes = await readFile(path.join(directory, 'runtime-build.json'));
	const manifest = JSON.parse(manifestBytes.toString('utf8'));
	if (
		manifest.schemaVersion !== 1 ||
		manifest.language !== 'SML' ||
		manifest.implementation?.name !== 'HaMLet' ||
		manifest.implementation?.version !== '2.0.1' ||
		manifest.implementation?.sha256 !== sourceSha256 ||
		manifest.implementation?.bytes !== 655727 ||
		manifest.producer?.target !== 'wasm32-wasip1' ||
		manifest.producer?.mlton !== '20241230' ||
		manifest.producer?.wasiSdk !== '33' ||
		!manifest.producer?.clang?.includes('22.1.0-wasi-sdk') ||
		JSON.stringify(manifest.producer?.sourcePins) !==
			JSON.stringify(JSON.parse(await readFile(path.join(producer, 'sources.json'), 'utf8')))
	)
		throw new Error('Sml runtime is not the pinned original console implementation');
	for (const name of [
		'build.py',
		'sources.json',
		'runner.sml',
		'node-wasi.mjs',
		'patches/embedding.patch',
		'patches/mlton-wasi-pointer.patch',
		'licenses/wasi-libraries.txt'
	]) {
		const expected = manifest.producer.inputs?.[name];
		if (
			JSON.stringify(receipt(await readFile(path.join(producer, name)))) !==
			JSON.stringify(expected)
		)
			throw new Error(`Sml build inputs changed: rebuild ${name} before syncing`);
	}
	const wasm = await readFile(path.join(directory, 'sml.wasm'));
	const license = await readFile(path.join(directory, 'LICENSE.txt'));
	const notices = await readFile(path.join(directory, 'THIRD_PARTY_NOTICES.txt'));
	/** @type {Array<[string, Buffer]>} */
	const files = [
		['sml.wasm', wasm],
		['LICENSE.txt', license],
		['THIRD_PARTY_NOTICES.txt', notices]
	];
	for (const [name, bytes] of files) {
		if (JSON.stringify(receipt(bytes)) !== JSON.stringify(manifest.artifacts?.[name]))
			throw new Error(`Sml ${name} does not match its producer receipt`);
	}
	if (
		wasm.byteLength > 20 * 1024 * 1024 ||
		!wasm.subarray(0, 4).equals(Buffer.from([0, 97, 115, 109]))
	)
		throw new Error('Invalid Sml WebAssembly artifact');
	return { manifestBytes, manifest, wasm, license, notices };
}

/**
 * Verify the committed interpreter; explicitly supplied producer output can refresh it.
 * @param {{ check?: boolean; sourceDir?: string; targetDir?: string; versionModulePath?: string }} options
 */
export async function syncWasmSmlAssets({
	check = false,
	sourceDir,
	targetDir = defaultTarget,
	versionModulePath = defaultVersionFile
} = {}) {
	const source = sourceDir ?? targetDir;
	const bundle = await verifyBundle(source);
	const wasmReceipt = bundle.manifest.artifacts['sml.wasm'];
	const profile =
		`// Generated by scripts/sync-wasm-sml.mjs.\n` +
		`import type { WasiInterpreterProfile } from './wasiInterpreters';\n\n` +
		`export const WASM_SML_INTERPRETER = Object.freeze(${JSON.stringify(
			{
				id: 'SML',
				folder: 'wasm-sml',
				fileName: 'sml.wasm',
				sourcePath: 'main.sml',
				command: 'sml',
				args: [],
				forwardProgramArgs: true,
				...wasmReceipt
			},
			null,
			2
		)} as const satisfies WasiInterpreterProfile);\n`;
	const profileBytes = Buffer.from(
		await format(profile, {
			...(await resolveConfig(versionModulePath)),
			parser: 'typescript'
		})
	);
	const outputs = new Map([
		[path.join(targetDir, 'sml.wasm'), bundle.wasm],
		[path.join(targetDir, 'LICENSE.txt'), bundle.license],
		[path.join(targetDir, 'THIRD_PARTY_NOTICES.txt'), bundle.notices],
		[path.join(targetDir, 'runtime-build.json'), bundle.manifestBytes],
		[versionModulePath, profileBytes]
	]);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error(`Sml runtime is stale: ${file}`);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return wasmReceipt;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const sourceIndex = process.argv.indexOf('--source');
	await syncWasmSmlAssets({
		check: process.argv.includes('--check'),
		sourceDir: sourceIndex < 0 ? undefined : process.argv[sourceIndex + 1]
	});
	console.log('Verified original HaMLet 2.0.1 Standard ML WASI interpreter and producer inputs');
}
