#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-bc');
const target = path.join(root, 'static/wasm-bc');
const versionFile = path.join(root, 'src/lib/playground/wasmBcVersion.ts');
const sourceHash = '91eb74caed0ee6655b669711a4f350c25579778694df248e28363318e03c7fc4';

/** @param {Uint8Array} data */
const receipt = (data) => ({
	bytes: data.byteLength,
	sha256: createHash('sha256').update(data).digest('hex')
});

/** @param {string} directory */
async function verifyBundle(directory) {
	const manifestBytes = await readFile(path.join(directory, 'runtime-build.json'));
	const manifest = JSON.parse(manifestBytes.toString('utf8'));
	if (
		manifest.schemaVersion !== 1 ||
		manifest.language !== 'BC' ||
		manifest.implementation?.name !== 'bc' ||
		manifest.implementation?.version !== '7.0.3' ||
		manifest.implementation?.sha256 !== sourceHash ||
		manifest.producer?.name !== 'wasi-sdk' ||
		manifest.producer?.version !== '33.0' ||
		manifest.producer?.target !== 'wasm32-wasi' ||
		!manifest.producer?.compiler?.startsWith('clang version 22.1.0-wasi-sdk') ||
		JSON.stringify(manifest.execution?.argv) !==
			'["bc","-q","-R","-f","<activePath>","...programArgs"]'
	)
		throw new Error('bc runtime is not the pinned original implementation');
	const inputs = [
		'build.py',
		'patches/wasi-signals.patch',
		'LICENSE.txt',
		'vendor/bc-7.0.3.tar.xz',
		...(await readdir(path.join(producer, 'licenses'))).sort().map((name) => `licenses/${name}`)
	];
	for (const name of inputs) {
		if (
			JSON.stringify(receipt(await readFile(path.join(producer, name)))) !==
			JSON.stringify(manifest.producer.inputs?.[name])
		)
			throw new Error(`bc producer input changed: rebuild ${name}`);
	}
	const files = new Map([['runtime-build.json', manifestBytes]]);
	for (const name of ['bc.wasm', 'LICENSE.txt', 'THIRD_PARTY_NOTICES.txt']) {
		const bytes = await readFile(path.join(directory, name));
		if (JSON.stringify(receipt(bytes)) !== JSON.stringify(manifest.artifacts?.[name]))
			throw new Error(`bc ${name} differs from its producer receipt`);
		files.set(name, bytes);
	}
	const wasm = files.get('bc.wasm');
	if (
		!wasm ||
		wasm.byteLength > 1024 * 1024 ||
		!wasm.subarray(0, 4).equals(Buffer.from([0, 97, 115, 109]))
	)
		throw new Error('Invalid bc WebAssembly artifact');
	return { files, wasm: manifest.artifacts['bc.wasm'] };
}

/** @param {{ check?: boolean; sourceDir?: string; targetDir?: string; versionModulePath?: string }} options */
export async function syncWasmBcAssets({
	check = false,
	sourceDir,
	targetDir = target,
	versionModulePath = versionFile
} = {}) {
	const bundle = await verifyBundle(sourceDir ?? targetDir);
	const source = `// Generated by scripts/sync-wasm-bc.mjs.\nimport type { WasiInterpreterProfile } from './wasiInterpreters';\n\nexport const WASM_BC_INTERPRETER = Object.freeze(${JSON.stringify({ id: 'BC', folder: 'wasm-bc', fileName: 'bc.wasm', sourcePath: 'main.bc', command: 'bc', args: ['-q', '-R', '-f'], forwardProgramArgs: true, ...bundle.wasm }, null, 2)} as const satisfies WasiInterpreterProfile);\n`;
	const profile = Buffer.from(
		await format(source, { ...(await resolveConfig(versionModulePath)), parser: 'typescript' })
	);
	const outputs = new Map(
		[...bundle.files].map(([name, bytes]) => [path.join(targetDir, name), bytes])
	);
	outputs.set(versionModulePath, profile);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes)) throw new Error(`Stale bc runtime: ${file}`);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return bundle.wasm;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const index = process.argv.indexOf('--source');
	await syncWasmBcAssets({
		check: process.argv.includes('--check'),
		sourceDir: index < 0 ? undefined : process.argv[index + 1]
	});
	console.log('Verified original bc 7.0.3 WASI runtime, licenses and producer inputs');
}
