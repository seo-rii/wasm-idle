import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';

const root = new URL('../', import.meta.url);
/** @typedef {{ source: string; bytes: number; sha256: string }} SourceReceipt */
/** @type {{version: string; revision: string; baseUrl: string; cmake: SourceReceipt; license: SourceReceipt; headers: Array<SourceReceipt & {path: string}>}} */
const lock = JSON.parse(
	await readFile(new URL('scripts/clang-resource-headers.lock.json', root), 'utf8')
);
/** @param {Uint8Array} bytes */
const sha256 = (bytes) => createHash('sha256').update(bytes).digest('hex');
/** @param {SourceReceipt} receipt */
const fetchPinned = async (receipt) => {
	const response = await fetch(new URL(receipt.source, lock.baseUrl), {
		signal: AbortSignal.timeout(60_000)
	});
	if (!response.ok) throw new Error(`${receipt.source}: HTTP ${response.status}`);
	const bytes = Buffer.from(await response.arrayBuffer());
	if (bytes.length !== receipt.bytes || sha256(bytes) !== receipt.sha256) {
		throw new Error(`${receipt.source}: LLVM source receipt mismatch`);
	}
	return bytes.toString('utf8');
};

const cmake = await fetchPinned(lock.cmake);
const coreFiles = cmake
	.match(/set\(core_files\s+([\s\S]*?)\s*\)/)?.[1]
	.split(/\s+/)
	.filter((name) => name !== 'module.modulemap');
if (JSON.stringify(coreFiles) !== JSON.stringify(lock.headers.map(({ path }) => path))) {
	throw new Error('Resource header list differs from the pinned LLVM core_files list');
}
/** @type {Record<string, string>} */
const headers = {};
for (let offset = 0; offset < lock.headers.length; offset += 4) {
	const batch = lock.headers.slice(offset, offset + 4);
	const sources = await Promise.all(batch.map(fetchPinned));
	for (let i = 0; i < batch.length; i++) headers[batch[i].path] = sources[i];
}
const license = await fetchPinned(lock.license);
const generated = `// Generated by scripts/sync-clang-resource-headers.mjs. Do not edit.
// LLVM ${lock.version}, Apache-2.0 WITH LLVM-exception; see LICENSE.llvm.txt.
export const CLANG_RESOURCE_HEADERS: Readonly<Record<string, string>> = Object.freeze(${JSON.stringify(headers, null, '\t')});
`;
await writeFile(
	new URL('packages/llvm-core/runtime/core/src/clang-resource-headers.generated.ts', root),
	generated
);
await writeFile(new URL('packages/llvm-core/LICENSE.llvm.txt', root), license);
console.log(
	`Synced ${lock.headers.length} LLVM ${lock.version} resource headers from ${lock.revision}.`
);
