#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { execFile } from 'node:child_process';
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const execute = promisify(execFile);
/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.byteLength,
	sha256: createHash('sha256').update(bytes).digest('hex')
});
/** @param {string} targetDir */
async function prepareOriginalAssets(targetDir) {
	await execute(
		'python3',
		[path.join(root, 'runtimes/wasm-moonbit/prepare.py'), '--output', targetDir],
		{ timeout: 300_000, maxBuffer: 1024 * 1024 }
	);
}

/** @param {{check?: boolean; targetDir?: string; profilePath?: string; prepareAssets?: (targetDir: string) => Promise<void>}} options */
export async function syncWasmMoonbitAssets({
	check = false,
	targetDir = path.join(root, 'static/wasm-moonbit'),
	profilePath = path.join(root, 'src/lib/playground/wasmMoonbitVersion.ts'),
	prepareAssets = prepareOriginalAssets
} = {}) {
	if (!check) {
		await mkdir(targetDir, { recursive: true });
		for (const name of [
			'upstream.json',
			'COMPILER-LICENSE.txt',
			'CORE-LICENSE.txt',
			'CORE-NOTICE.txt'
		]) {
			try {
				await readFile(path.join(targetDir, name));
			} catch (error) {
				if (
					!error ||
					typeof error !== 'object' ||
					!('code' in error) ||
					error.code !== 'ENOENT'
				)
					throw error;
				await copyFile(
					path.join(root, 'static/wasm-moonbit', name),
					path.join(targetDir, name)
				);
			}
		}
	}
	const manifest = JSON.parse(await readFile(path.join(targetDir, 'upstream.json'), 'utf8'));
	if (
		manifest.version !== '0.10.19+97801ee1b' ||
		manifest.revision !== 'd4ada10d212b5376f7f8bf49cd2fbaa275a395df' ||
		manifest.archive?.sha256 !==
			'ab55f4d92206916308922c768033d8a1b0eef5a2a3ea4c3ba8569c52cd40e2a9' ||
		manifest.assets?.['stdlib.tar']?.sha256 !==
			'c4f7c594c6e900395ec7afe0b1fcbb01452b65587a7303f63710e6db74598500' ||
		manifest.source?.modified !== false
	)
		throw new Error('MoonBit runtime is not the pinned original compiler/core');
	const entries = Object.entries({ ...manifest.assets, ...manifest.notices });
	const missing = [];
	for (const [name, pin] of entries) {
		try {
			if (
				JSON.stringify(receipt(await readFile(path.join(targetDir, name)))) !==
				JSON.stringify(pin)
			)
				throw new Error('MoonBit source receipt mismatch: ' + name);
		} catch (error) {
			if (
				!error ||
				typeof error !== 'object' ||
				!('code' in error) ||
				error.code !== 'ENOENT'
			)
				throw error;
			missing.push(name);
		}
	}
	if (missing.length) {
		if (check)
			throw new Error(
				'Missing MoonBit assets: ' +
					missing.join(', ') +
					'; run node scripts/sync-wasm-moonbit.mjs'
			);
		await prepareAssets(targetDir);
		for (const [name, pin] of entries)
			if (
				JSON.stringify(receipt(await readFile(path.join(targetDir, name)))) !==
				JSON.stringify(pin)
			)
				throw new Error('MoonBit source receipt mismatch: ' + name);
	}
	const configuration = await resolveConfig(path.join(root, 'package.json'));
	const source = await readFile(
		path.join(root, 'scripts/runtime-workers/wasm-moonbit-runner-worker.js'),
		'utf8'
	);
	const worker = await format(
		source.replace('__WASM_IDLE_MOONBIT_DISTRIBUTION__', JSON.stringify(manifest)),
		{ ...configuration, parser: 'babel' }
	);
	const profile = await format(
		`// Generated by scripts/sync-wasm-moonbit.mjs.\nexport const WASM_MOONBIT_RUNTIME = Object.freeze(${JSON.stringify({ version: manifest.version, folder: 'wasm-moonbit', worker: receipt(Buffer.from(worker)) })} as const);\n`,
		{ ...configuration, parser: 'typescript' }
	);
	for (const [file, content] of [
		[path.join(targetDir, 'runner-worker.js'), worker],
		[profilePath, profile]
	]) {
		if (check) {
			if ((await readFile(file, 'utf8')) !== content)
				throw new Error('Stale generated MoonBit asset: ' + file);
		} else await writeFile(file, content);
	}
	return manifest;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await syncWasmMoonbitAssets({ check: process.argv.includes('--check') });
	console.log('Verified original MoonBit compiler/core and generated browser host');
}
