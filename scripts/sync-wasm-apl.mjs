#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-apl');
const defaultTarget = path.join(root, 'static/wasm-apl');
const defaultVersionFile = path.join(root, 'src/lib/playground/wasmAplVersion.ts');
const sourceSha256 = '24bbb744fce47e62837234a053bdeecee51b9ea61c82c79f7cc191bc6a54c0a1';

/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.byteLength,
	sha256: createHash('sha256').update(bytes).digest('hex')
});
/** @param {unknown} a @param {unknown} b */
const equal = (a, b) => JSON.stringify(a) === JSON.stringify(b);

/** @param {string} directory */
async function verifyBundle(directory) {
	const manifestBytes = await readFile(path.join(directory, 'runtime-build.json'));
	const manifest = JSON.parse(manifestBytes.toString('utf8'));
	const pins = JSON.parse(await readFile(path.join(producer, 'source-pins.json'), 'utf8'));
	if (
		manifest.format !== 'wasm-apl-build-v1' ||
		manifest.version !== '2.0' ||
		manifest.source?.name !== 'GNU APL' ||
		manifest.source?.sha256 !== sourceSha256 ||
		manifest.source?.bytes !== 5128916 ||
		manifest.source?.license !== 'GPL-3.0-or-later' ||
		!equal(manifest.source, pins.runtime) ||
		manifest.toolchain?.name !== 'wasi-sdk' ||
		manifest.toolchain?.version !== '33.0' ||
		manifest.toolchain?.llvmRevision !== pins.toolchain.llvmRevision ||
		!manifest.toolchain?.compiler?.includes('22.1.0-wasi-sdk') ||
		manifest.configuration?.memoryLimitBytes !== 256 * 1024 * 1024 ||
		!manifest.configuration?.compilerFlags?.includes('--no-wasm-opt') ||
		!manifest.configuration?.compilerFlags?.includes('-fwasm-exceptions') ||
		!manifest.configuration?.compilerFlags?.includes('-wasm-use-legacy-eh=false')
	)
		throw new Error('APL runtime is not the pinned original GNU APL console implementation');
	const inputs = [
		'build.py',
		'source-pins.json',
		'wasi-platform.patch',
		'port/termios.h',
		'port/netdb.h',
		'port/wasi-host.h',
		'port/wasi-host.cc',
		pins.runtime.licenseFile.path,
		...pins.licenses.map((/** @type {{ path: string }} */ pin) => pin.path)
	];
	if (!equal([...Object.keys(manifest.inputs ?? {})].sort(), [...inputs].sort()))
		throw new Error('GNU APL producer input inventory is incomplete');
	for (const name of inputs) {
		if (!equal(receipt(await readFile(path.join(producer, name))), manifest.inputs[name]))
			throw new Error(`GNU APL producer input changed: rebuild ${name} before syncing`);
	}
	const files = new Map();
	for (const name of ['apl.wasm', 'LICENSE', 'THIRD_PARTY_NOTICES.txt']) {
		const bytes = await readFile(path.join(directory, name));
		if (!equal(receipt(bytes), manifest.files?.[name]))
			throw new Error(`GNU APL ${name} does not match its producer receipt`);
		files.set(name, bytes);
	}
	const wasm = files.get('apl.wasm');
	if (!wasm || wasm.length > 3_000_000) throw new Error('Invalid GNU APL WebAssembly size');
	const module = new WebAssembly.Module(wasm);
	if (
		WebAssembly.Module.imports(module).some(
			(entry) => entry.module !== 'wasi_snapshot_preview1'
		)
	)
		throw new Error('GNU APL imports a non-WASI host runtime');
	const exports = WebAssembly.Module.exports(module);
	for (const [name, kind] of [
		['_start', 'function'],
		['memory', 'memory']
	]) {
		if (!exports.some((entry) => entry.name === name && entry.kind === kind))
			throw new Error(`GNU APL does not export ${name}`);
	}
	files.set('runtime-build.json', manifestBytes);
	return { manifest, files };
}

/**
 * Verify committed assets, or copy explicitly supplied producer output.
 * @param {{ check?: boolean; sourceDir?: string; targetDir?: string; versionModulePath?: string }} options
 */
export async function syncWasmAplAssets({
	check = false,
	sourceDir,
	targetDir = defaultTarget,
	versionModulePath = defaultVersionFile
} = {}) {
	const bundle = await verifyBundle(sourceDir ?? targetDir);
	const wasmReceipt = bundle.manifest.files['apl.wasm'];
	const profile =
		`// Generated by scripts/sync-wasm-apl.mjs.\n` +
		`import type { WasiInterpreterProfile } from './wasiInterpreters';\n\n` +
		`export const WASM_APL_INTERPRETER = Object.freeze(${JSON.stringify(
			{
				id: 'APL',
				folder: 'wasm-apl',
				fileName: 'apl.wasm',
				sourcePath: 'main.apl',
				maxSourcePathBytes: 4094,
				command: 'apl',
				args: ['--script', '--rawCIN', '--OFF', '--noSV', '-f'],
				forwardProgramArgs: true,
				programArgsPrefix: ['--'],
				...wasmReceipt
			},
			null,
			2
		)} as const satisfies WasiInterpreterProfile);\n`;
	const profileBytes = Buffer.from(
		await format(profile, {
			...(await resolveConfig(versionModulePath)),
			parser: 'typescript'
		})
	);
	const outputs = new Map(
		[...bundle.files].map(([name, bytes]) => [path.join(targetDir, name), bytes])
	);
	outputs.set(versionModulePath, profileBytes);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error(`GNU APL runtime is stale: ${file}`);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return wasmReceipt;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const sourceIndex = process.argv.indexOf('--source');
	await syncWasmAplAssets({
		check: process.argv.includes('--check'),
		sourceDir: sourceIndex < 0 ? undefined : process.argv[sourceIndex + 1]
	});
	console.log('Verified original GNU APL 2.0 WASI console and all producer inputs');
}
