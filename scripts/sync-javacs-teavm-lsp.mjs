import { createHash, randomUUID } from 'node:crypto';
import { cp, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createJavacsCspRuntime } from './teavm/javacs-csp-runtime.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const LOCK = path.join(ROOT, 'scripts/javacs-teavm-lsp-assets.lock.json');
const GENERATED = path.join(ROOT, 'packages/lsp/src/java/assets.generated.ts');
const ASSETS = ['javacs-runtime.mjs', 'javacs.wasm', 'jdk-platform.zip'];

/** @param {{source?:string, target?:string, updateLock?:boolean}} [options] */
export async function syncJavacsTeavmLsp(options = {}) {
	const source = path.resolve(
		options.source || path.join(ROOT, 'producers/javacs-teavm/build/dist')
	);
	const target = path.resolve(options.target || path.join(ROOT, 'static/wasm-java-lsp'));
	if (
		source === target ||
		source.startsWith(`${target}${path.sep}`) ||
		target.startsWith(`${source}${path.sep}`)
	) {
		throw new Error('Java LSP source and target directories must be separate');
	}
	const provenance = JSON.parse(await readFile(path.join(source, 'provenance.json'), 'utf8'));
	if (
		provenance.sourceRevision !== '7fffb6c5929fe02c52e1c823ae990bad2b540ad1' ||
		provenance.teavmVersion !== '0.16.0'
	)
		throw new Error('Unexpected javacs / TeaVM producer provenance');
	const bodyBytes = await readFile(path.join(source, 'jso-bodies.json'));
	const bodies = JSON.parse(bodyBytes.toString('utf8'));
	const adapterBytes = await readFile(new URL('./teavm/javacs-csp-runtime.mjs', import.meta.url));
	const hostAdapter = {
		path: 'scripts/teavm/javacs-csp-runtime.mjs',
		bytes: adapterBytes.length,
		sha256: createHash('sha256').update(adapterBytes).digest('hex')
	};
	const payload = await Promise.all(
		ASSETS.map(async (filename) => {
			const original = await readFile(path.join(source, filename));
			const bytes =
				filename === 'javacs-runtime.mjs'
					? Buffer.from(createJavacsCspRuntime(original.toString('utf8'), bodies))
					: original;
			if (!bytes.length || bytes.length > 128 * 1024 * 1024)
				throw new Error(`Invalid Java LSP asset size: ${filename}`);
			return {
				bytes,
				sourceReceipt: {
					path: filename,
					bytes: original.length,
					sha256: createHash('sha256').update(original).digest('hex')
				},
				receipt: {
					path: filename,
					bytes: bytes.length,
					sha256: createHash('sha256').update(bytes).digest('hex')
				}
			};
		})
	);
	if (payload[1].bytes.subarray(0, 4).toString('hex') !== '0061736d')
		throw new Error('Java LSP producer output is not WebAssembly');
	for (const receipt of [
		...payload.map(({ sourceReceipt }) => sourceReceipt),
		{
			path: 'jso-bodies.json',
			bytes: bodyBytes.length,
			sha256: createHash('sha256').update(bodyBytes).digest('hex')
		}
	]) {
		const reported = provenance.assets?.find((asset) => asset.path === receipt.path);
		if (reported?.bytes !== receipt.bytes || reported?.sha256 !== receipt.sha256)
			throw new Error(`Java LSP producer provenance does not match ${receipt.path}`);
	}
	if (options.updateLock) {
		await writeFile(
			LOCK,
			`${JSON.stringify({ schema: 'wasm-idle-javacs-teavm-lsp-v1', provenance, hostAdapter, assets: payload.map(({ receipt }) => receipt) }, null, '\t')}\n`
		);
	}
	const lock = JSON.parse(await readFile(LOCK, 'utf8'));
	if (
		lock.schema !== 'wasm-idle-javacs-teavm-lsp-v1' ||
		JSON.stringify(lock.provenance) !== JSON.stringify(provenance) ||
		JSON.stringify(lock.hostAdapter) !== JSON.stringify(hostAdapter) ||
		JSON.stringify(lock.assets) !== JSON.stringify(payload.map(({ receipt }) => receipt))
	) {
		throw new Error('Java LSP producer output does not match pinned size / SHA-256 receipts');
	}
	const generated =
		'// Generated by scripts/sync-javacs-teavm-lsp.mjs from verified producer bytes.\n' +
		'export const JAVA_LANGUAGE_SERVER_ASSETS = [\n' +
		lock.assets
			.map(
				(asset) =>
					`\t{\n\t\tpath: '${asset.path}',\n\t\tbytes: ${asset.bytes},\n\t\tsha256: '${asset.sha256}'\n\t}`
			)
			.join(',\n') +
		'\n] as const;\n';
	if (options.updateLock) await writeFile(GENERATED, generated);
	else if ((await readFile(GENERATED, 'utf8')) !== generated)
		throw new Error('Java LSP SDK receipts are stale; regenerate and review the lock');
	const temporary = `${target}.preparing-${randomUUID()}`;
	const previous = `${target}.previous-${randomUUID()}`;
	let backedUp = false;
	await mkdir(temporary, { recursive: true });
	try {
		for (const { bytes, receipt } of payload)
			await writeFile(path.join(temporary, receipt.path), bytes);
		await cp(path.join(source, 'notices'), path.join(temporary, 'notices'), {
			recursive: true
		});
		await writeFile(
			path.join(temporary, 'provenance.json'),
			`${JSON.stringify(lock.provenance, null, 2)}\n`
		);
		await mkdir(path.dirname(target), { recursive: true });
		try {
			await rename(target, previous);
			backedUp = true;
		} catch (error) {
			if (error.code !== 'ENOENT') throw error;
		}
		try {
			await rename(temporary, target);
		} catch (error) {
			if (backedUp) await rename(previous, target);
			throw error;
		}
		if (backedUp) await rm(previous, { recursive: true, force: true });
	} finally {
		await rm(temporary, { recursive: true, force: true });
	}
	return { target, assets: lock.assets };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const args = process.argv.slice(2);
	const options = {};
	while (args.length) {
		const argument = args.shift();
		if (argument === '--update-lock') options.updateLock = true;
		else if (argument === '--source' && args.length) options.source = args.shift();
		else if (argument === '--target' && args.length) options.target = args.shift();
		else throw new Error(`Unknown or incomplete argument: ${argument}`);
	}
	console.log(JSON.stringify(await syncJavacsTeavmLsp(options), null, 2));
}
