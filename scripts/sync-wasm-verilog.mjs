#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { gzipSync, gunzipSync } from 'node:zlib';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-verilog');
const defaultTarget = path.join(root, 'static/wasm-verilog');
const versionFile = path.join(root, 'src/lib/playground/wasmVerilogVersion.ts');
/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.length,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

/** @param {{check?: boolean; download?: boolean; targetDir?: string; versionModulePath?: string}} options */
export async function syncWasmVerilogAssets({
	check = false,
	download = false,
	targetDir = defaultTarget,
	versionModulePath = versionFile
} = {}) {
	const pin = JSON.parse(await readFile(path.join(producer, 'upstream.json'), 'utf8'));
	if (
		pin.implementation.revision !== 'c7530dbcc186de2f21eacde14fd28061b885924c' ||
		pin.port.revision !== 'ab0ff3862a8cf8c6535117a64d370c4bf263042f'
	)
		throw new Error('Verilog upstream implementation pin changed');
	const profile = { profileId: 'icarus-14-c7530db-verisim-ab0ff386-v1', assets: pin.assets };
	const outputs = new Map();
	/** @type {Record<string, {path: string; bytes: number; sha256: string}>} */
	const delivery = {};
	for (const [name, expected] of Object.entries(pin.assets)) {
		let bytes;
		if (download) {
			const url = `https://raw.githubusercontent.com/senolgulgonul/verisim/${pin.port.revision}/${name}`;
			const response = await fetch(url, { redirect: 'error' });
			if (!response.ok) throw new Error(`Verilog download failed: ${response.status}`);
			bytes = Buffer.from(await response.arrayBuffer());
		} else {
			try {
				bytes = gunzipSync(await readFile(path.join(targetDir, name + '.gz.bin')), {
					maxOutputLength: expected.bytes
				});
			} catch (error) {
				// Permit an original producer output to bootstrap the pinned delivery bundle.
				if (!(
					error &&
					typeof error === 'object' &&
					'code' in error &&
					error.code === 'ENOENT'
				))
					throw error;
				bytes = await readFile(path.join(targetDir, name));
			}
		}
		if (JSON.stringify(receipt(bytes)) !== JSON.stringify(expected))
			throw new Error(`Verilog pinned asset changed: ${name}`);
		const compressed = gzipSync(bytes, { level: 9 });
		delivery[name] = { path: name + '.gz.bin', ...receipt(compressed) };
		outputs.set(path.join(targetDir, name + '.gz.bin'), compressed);
	}
	const host = (
		await readFile(path.join(root, 'scripts/runtime-workers/verilog-host.mjs'), 'utf8')
	).replaceAll('export function ', 'function ');
	const template = await readFile(
		path.join(root, 'scripts/runtime-workers/wasm-verilog-runner-worker.js'),
		'utf8'
	);
	const worker = Buffer.from(
		host + '\n' + template.replace('__WASM_IDLE_VERILOG_PROFILE__', JSON.stringify(profile))
	);
	const workerReceipt = receipt(worker);
	outputs.set(path.join(targetDir, 'runner-worker.js'), worker);
	for (const name of ['LICENSE.iverilog', 'LICENSE.emscripten'])
		outputs.set(path.join(targetDir, name), await readFile(path.join(producer, name)));
	/** @type {Record<string, {bytes: number; sha256: string}>} */
	const inputs = {};
	for (const name of ['upstream.json', 'upstream-build.sh', 'iverilog-wasm.patch'])
		inputs[name] = receipt(await readFile(path.join(producer, name)));
	const manifest = Buffer.from(
		JSON.stringify(
			{
				schemaVersion: 1,
				language: 'VERILOG',
				...pin,
				delivery,
				worker: workerReceipt,
				inputs
			},
			null,
			2
		) + '\n'
	);
	outputs.set(path.join(targetDir, 'runtime-build.json'), manifest);
	const moduleSource = `// Generated by scripts/sync-wasm-verilog.mjs.\nexport const VERILOG_PROFILE = ${JSON.stringify(profile)} as const;\nexport const VERILOG_DELIVERY = ${JSON.stringify(delivery)} as const;\nexport const VERILOG_WORKER_RECEIPT = ${JSON.stringify(workerReceipt)} as const;\nexport const VERILOG_MANIFEST_RECEIPT = ${JSON.stringify(receipt(manifest))} as const;\n`;
	outputs.set(
		versionModulePath,
		Buffer.from(
			await format(moduleSource, {
				...(await resolveConfig(versionModulePath)),
				parser: 'typescript'
			})
		)
	);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error(`Stale Verilog runtime: ${file}`);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return { profile, workerReceipt, manifestReceipt: receipt(manifest) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await syncWasmVerilogAssets({
		check: process.argv.includes('--check'),
		download: process.argv.includes('--download')
	});
	console.log('Verified original Icarus Verilog compiler, simulator and pinned port assets');
}
