#!/usr/bin/env node
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { promisify } from 'node:util';
import { format, resolveConfig } from 'prettier';

const execute = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const producer = path.join(root, 'runtimes/wasm-smalltalk');
/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.length,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

/** @param {{check?: boolean; targetDir?: string; versionModulePath?: string}} options */
export async function syncWasmSmalltalkAssets({
	check = false,
	targetDir = path.join(root, 'static/wasm-smalltalk'),
	versionModulePath = path.join(root, 'src/lib/playground/wasmSmalltalkVersion.ts')
} = {}) {
	const { stdout } = await execute('python3', [
		path.join(producer, 'build.py'),
		'--target-dir',
		targetDir,
		...(check ? ['--check'] : [])
	]);
	const profile = { profileId: 'amber-0.32.0-requirejs-2.3.8-v1', assets: JSON.parse(stdout) };
	const template = await readFile(
		path.join(root, 'scripts/runtime-workers/wasm-smalltalk-runner-worker.js'),
		'utf8'
	);
	const worker = Buffer.from(
		template.replace('__WASM_IDLE_SMALLTALK_PROFILE__', JSON.stringify(profile))
	);
	const workerReceipt = receipt(worker);
	/** @type {Record<string, {bytes: number; sha256: string}>} */
	const inputs = {};
	for (const name of ['upstream.json', 'build.py'])
		inputs[name] = receipt(await readFile(path.join(producer, name)));
	inputs['runner-worker.source.js'] = receipt(Buffer.from(template));
	const pin = JSON.parse(await readFile(path.join(producer, 'upstream.json'), 'utf8'));
	const manifest = Buffer.from(
		JSON.stringify(
			{
				schemaVersion: 1,
				language: 'SMALLTALK',
				...pin,
				...profile,
				worker: workerReceipt,
				inputs
			},
			null,
			2
		) + '\n'
	);
	const manifestReceipt = receipt(manifest);
	const module = `// Generated by scripts/sync-wasm-smalltalk.mjs.\nexport const SMALLTALK_PROFILE = ${JSON.stringify(profile)} as const;\nexport const SMALLTALK_WORKER_RECEIPT = ${JSON.stringify(workerReceipt)} as const;\nexport const SMALLTALK_MANIFEST_RECEIPT = ${JSON.stringify(manifestReceipt)} as const;\n`;
	const outputs = new Map([
		[path.join(targetDir, 'runner-worker.js'), worker],
		[path.join(targetDir, 'runtime-build.json'), manifest],
		[
			versionModulePath,
			Buffer.from(
				await format(module, {
					...(await resolveConfig(versionModulePath)),
					parser: 'typescript'
				})
			)
		]
	]);
	for (const [file, bytes] of outputs) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error('Stale Smalltalk runtime: ' + file);
		} else {
			await mkdir(path.dirname(file), { recursive: true });
			await writeFile(file, bytes);
		}
	}
	return { profile, workerReceipt, manifestReceipt };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await syncWasmSmalltalkAssets({ check: process.argv.includes('--check') });
	console.log('Verified original Amber Smalltalk compiler, kernel and AMD loader');
}
