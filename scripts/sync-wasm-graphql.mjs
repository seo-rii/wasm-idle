#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { build, version as esbuildVersion } from 'esbuild';
import { format, resolveConfig } from 'prettier';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
export const GRAPHQL_VERSION = '17.0.2';
export const GRAPHQL_STATIC_DIR = path.join(root, 'static/wasm-graphql');
const profileFile = path.join(root, 'src/lib/playground/wasmGraphqlVersion.ts');
/** @param {Uint8Array} bytes */
const receipt = (bytes) => ({
	bytes: bytes.length,
	sha256: createHash('sha256').update(bytes).digest('hex')
});

export async function buildGraphqlAssets() {
	const entryDirectory = path.dirname(require.resolve('graphql'));
	// graphql's development export lives in __dev__; package metadata remains at its root.
	const packageDirectory =
		path.basename(entryDirectory) === '__dev__' ? path.dirname(entryDirectory) : entryDirectory;
	const manifest = JSON.parse(
		await readFile(path.join(packageDirectory, 'package.json'), 'utf8')
	);
	if (manifest.version !== GRAPHQL_VERSION)
		throw new Error(`Expected graphql@${GRAPHQL_VERSION}, got ${manifest.version}`);
	const built = await build({
		absWorkingDir: root,
		entryPoints: ['scripts/runtime-workers/wasm-graphql-runner-worker.ts'],
		bundle: true,
		tsconfigRaw: { compilerOptions: {} },
		write: false,
		platform: 'browser',
		format: 'iife',
		target: 'es2022',
		minify: true,
		legalComments: 'inline',
		define: { 'process.env.NODE_ENV': '"production"' }
	});
	const worker = Buffer.from(built.outputFiles[0].contents);
	const workerReceipt = receipt(worker);
	const license = await readFile(path.join(packageDirectory, 'LICENSE'));
	const runtimeManifest = Buffer.from(
		`${JSON.stringify(
			{
				schemaVersion: 1,
				language: 'GRAPHQL',
				implementation: { package: 'graphql', version: GRAPHQL_VERSION, license: 'MIT' },
				build: {
					tool: 'esbuild',
					version: esbuildVersion,
					platform: 'browser',
					format: 'iife',
					target: 'es2022'
				},
				artifacts: { 'runner-worker.js': workerReceipt, 'LICENSE.txt': receipt(license) }
			},
			null,
			2
		)}\n`
	);
	const profile = `// Generated by scripts/sync-wasm-graphql.mjs.\nexport const WASM_GRAPHQL_VERSION = '${GRAPHQL_VERSION}';\nexport const WASM_GRAPHQL_RUNNER_RECEIPT = ${JSON.stringify(workerReceipt, null, '\t')} as const;\n`;
	return {
		worker,
		license,
		runtimeManifest,
		profile: await format(profile, {
			...(await resolveConfig(profileFile)),
			parser: 'typescript'
		})
	};
}

export async function syncWasmGraphqlAssets({
	check = false,
	targetDir = GRAPHQL_STATIC_DIR
} = {}) {
	const generated = await buildGraphqlAssets();
	const files = new Map([
		[path.join(targetDir, 'runner-worker.js'), generated.worker],
		[path.join(targetDir, 'LICENSE.txt'), generated.license],
		[path.join(targetDir, 'runtime-manifest.v1.json'), generated.runtimeManifest],
		[profileFile, Buffer.from(generated.profile)]
	]);
	if (!check) await mkdir(targetDir, { recursive: true });
	for (const [file, bytes] of files) {
		if (check) {
			if (!(await readFile(file)).equals(bytes))
				throw new Error(`GraphQL asset is stale: ${path.relative(root, file)}`);
		} else await writeFile(file, bytes);
	}
	return { sourceDir: path.join(root, 'scripts/runtime-workers'), targetDir };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	await syncWasmGraphqlAssets({ check: process.argv.includes('--check') });
	console.log(
		`GraphQL ${GRAPHQL_VERSION} browser assets ${process.argv.includes('--check') ? 'verified' : 'generated'}`
	);
}
